"""Contract C1 (P4-1): the Azerbaijani anchors and carrier sentences the
targeted builder fills with values and decoys.

    ANCHORS: dict[str, list[str]]  label -> anchor forms that go into "{a}"
    FRAMES: dict[str, list[str]]   label -> carrier sentences: one value slot,
                                   "{v}" or "{v:CASE}", and an optional "{a}"
    GENERIC_FRAMES: list[str]      label-agnostic "section + verb" frames
    NEUTRAL: list[str]             filler sentences with no PII and no digits
    FRAME_VERSION: str

Written from scratch, not from the benchmark (A2 rule 3). The builder picks
this file up instead of `frames_az_stub.py`. `test_frames.py` checks every
rule below.

Grammar rules:
- `{a}` gets any form of `ANCHORS[label]`, so every form is a noun phrase in
  the nominative or the possessive, and it reads right before a passive or
  intransitive verb: "... doğum tarixi {v} kimi göstərilib". A possessor goes
  inside the anchor ("müştərinin yaşı"), never in the frame right before
  `{a}`: "Müqavilənin {a}" breaks with the bare form "tarix", and "şəxsin
  {a}" doubles with "müştərinin yaşı".
- The accusative, locative, dative and first-person anchors (`tarixini`,
  `tarixində`, `tarixinə`, `tarixim`) fit no passive frame. They are written
  into their own active-voice frames instead.
- `{v:CASE}` (RC8, D-9): the sentence needs that case, and the team's
  renderer (P2-4c) adds the suffix with vowel harmony. The label covers the
  value + suffix. Honorifics take the case themselves ("{v} bəyə"), so their
  name slot stays bare.
- Folded frames are written with `_f`, which folds the whole sentence. The
  builder folds the anchor to match.
"""

